#!/usr/bin/env node
/* global require, __dirname, process, console */
// Deterministic credential-policy generator for the TypeScript and Python
// consumers. --check is read-only and fails on stale or tampered output.

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const manifestPath = path.join(__dirname, 'credential-policy-v0.json');
const tsPath = path.join(__dirname, '..', '..', 'src', 'assembly', 'credential-policy-v0.generated.ts');
const pyPath = path.join(__dirname, 'credential_policy_v0_generated.py');

function render() {
  const raw = fs.readFileSync(manifestPath);
  const manifest = JSON.parse(raw.toString('utf8'));
  if (manifest.version !== 'credential-policy-v0' || !Array.isArray(manifest.rules)) {
    throw new Error('credential manifest has an unsupported shape');
  }
  const ids = new Set();
  for (const rule of manifest.rules) {
    if (!/^[a-z][a-z0-9_]*$/.test(rule.id) || ids.has(rule.id)) throw new Error('credential rule id is invalid or duplicate');
    if (typeof rule.pattern !== 'string' || !['', 'i'].includes(rule.flags)) throw new Error(`credential rule ${rule.id} is invalid`);
    ids.add(rule.id);
    new RegExp(rule.pattern, rule.flags);
  }
  const sha = crypto.createHash('sha256').update(raw).digest('hex');
  const tuples = manifest.rules.map((rule) => [rule.id, rule.pattern, rule.flags]);
  const ts = [
    '// Generated by test/assembly/generate-credential-policy.js. DO NOT EDIT.',
    `export const CREDENTIAL_POLICY_MANIFEST_SHA256 = '${sha}';`,
    `export const CREDENTIAL_RULES = ${JSON.stringify(tuples, null, 2)} as const;`,
    '',
  ].join('\n');
  const py = [
    '# Generated by generate-credential-policy.js. DO NOT EDIT.',
    `MANIFEST_SHA256 = ${JSON.stringify(sha)}`,
    `CREDENTIAL_RULES = ${JSON.stringify(tuples, null, 2)}`
      .replace(/\bnull\b/g, 'None'),
    '',
  ].join('\n');
  return [[tsPath, ts], [pyPath, py]];
}

function main() {
  const check = process.argv.slice(2).includes('--check');
  let stale = false;
  for (const [target, expected] of render()) {
    if (check) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
        console.error(`STALE ${path.relative(__dirname, target)}`);
        stale = true;
      }
    } else {
      fs.writeFileSync(target, expected, 'utf8');
    }
  }
  if (stale) process.exitCode = 1;
  else console.log(check ? 'Credential policy outputs are current.' : 'Generated credential policy outputs.');
}

main();
