#!/usr/bin/env python3
"""Generate Unicode classes matching the pinned kb-sync Python3.12 scanner.
No corpus, credential, network or database input is consumed.
"""
from pathlib import Path
import unicodedata

assert unicodedata.unidata_version == '15.0.0', 'Use the scanner Unicode15 runtime'

def ranges(predicate):
    result = []
    start = end = None
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start is None:
                start = end = codepoint
            elif codepoint == end + 1:
                end = codepoint
            else:
                result.append((start, end))
                start = end = codepoint
        elif start is not None:
            result.append((start, end))
            start = end = None
    if start is not None:
        result.append((start, end))
    return ''.join('\\u{' + format(a, 'x') + '}' +
                   ('' if a == b else '-\\u{' + format(b, 'x') + '}') for a, b in result)

word = ranges(lambda char: char.isalnum() or char == '_')
space = ranges(str.isspace)
target = Path(__file__).resolve().parents[1] / 'apps/api/src/tasks/redactions/python-secret-classes.ts'
target.write_text('// Generated by dev-tools/generate-python-secret-classes.py.\n'
                  '// Python3.12 / Unicode15: re Unicode word and whitespace classes.\n'
                  '// Do not replace with Node Unicode properties: Node uses a newer table.\n'
                  "export const PYTHON_SECRET_UNICODE_VERSION = '15.0.0';\n"
                  'export const PYTHON_SECRET_WORD_CLASS = String.raw`' + word + '`;\n'
                  'export const PYTHON_SECRET_SPACE_CLASS = String.raw`' + space + '`;\n')
